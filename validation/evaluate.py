"""Compare the baseline and calibrated configurations with the reference data and write the validation report.

    python3 -m validation.evaluate            # writes validation/reports/validation_report.md and prints it

2024 data was used to calibrate; 2025 is held out. Results are reported for both, labelled.
"""
import statistics
from pathlib import Path

from cars import CARS
from tracks import CIRCUITS, Monza
from validation import metrics, reference
from validation.model import flying_laps, load_config, race_time

REPORT = Path(__file__).resolve().parent / "reports" / "validation_report.md"
SEASONS = {2024: "training", 2025: "held out"}  # 2024 is the calibration data
CONFIGS = ("baseline", "calibrated")


def qualifying(config: dict, season: int) -> dict:
    best = reference.qualifying_best(season)
    teams = sorted(best, key=lambda team: best[team][0])
    model = flying_laps(config, teams)
    ref, sim = [best[t][0] for t in teams], [model[t] for t in teams]
    return {
        "rows": [(t, best[t][1], best[t][0], model[t]) for t in teams],
        "mae": metrics.mean_absolute_error(sim, ref),
        "bias": metrics.mean_error(sim, ref),
        "mape": metrics.mean_absolute_percentage_error(sim, ref),
        "max": metrics.max_absolute_error(sim, ref),
        "fastest": (teams[0], min(model, key=model.get)),
    }


def pit_loss(config: dict, season: int) -> dict:
    losses = [stop["loss"] for stop in reference.pit_losses(season)]
    return {
        "n": len(losses),
        "median": statistics.median(losses),
        "range": (min(losses), max(losses)),
        "model": config["pit_loss"],
        "mae": metrics.mean_absolute_error([config["pit_loss"]] * len(losses), losses),
    }


def race(config: dict, season: int) -> dict:
    won = reference.winner(season)
    model = race_time(config, won["team"], won["laps"], won["stop_laps"])
    return {**won, "model": model}


def circuits(configs: dict) -> list[tuple]:
    """Per circuit: (name, straight scale, lap record, fastest model car's flying lap per config)."""
    rows = []
    for name, circuit in CIRCUITS.items():
        track = circuit()
        laps = {config: min(flying_laps(c, CARS, track).values()) for config, c in configs.items()}
        rows.append((name, track.straight_scale, track.lap_record, laps))
    return rows


def evaluate() -> dict:
    configs = {name: load_config(name) for name in CONFIGS}
    length = reference.track_length(2024)
    return {
        "configs": configs,
        "length": (Monza().length, length),
        "qualifying": {(n, s): qualifying(c, s) for n, c in configs.items() for s in SEASONS},
        "pit_loss": {(n, s): pit_loss(c, s) for n, c in configs.items() for s in SEASONS},
        "race": {(n, s): race(c, s) for n, c in configs.items() for s in SEASONS},
        "circuits": circuits(configs),
    }


def render(result: dict) -> str:
    configs = result["configs"]
    model_length, ref_length = result["length"]
    lines = [
        "# Validation report (generated)",
        "",
        "Generated by `python3 -m validation.evaluate` from `data/reference/raw/` (Jolpica-F1 / Ergast data, CC BY-NC-SA 4.0).",
        "Do not edit by hand. 2024 = data used for calibration; 2025 = held out. Errors are model minus reference.",
        "",
        "## Configurations",
        "",
        "| Config | tyre_grip | pit_loss (s) |",
        "|---|---|---|",
        *(f"| {name} | {c['tyre_grip']} | {c['pit_loss']} |" for name, c in configs.items()),
        "",
        "## Track length (not calibrated; since V9 the model lap is built to the official length)",
        "",
        "| Model Monza (m) | Reference (m) | Error (m) | Relative error |",
        "|---|---|---|---|",
        f"| {model_length:.1f} | {ref_length:.1f} | {metrics.error(model_length, ref_length):+.1f} "
        f"| {100 * metrics.relative_error(model_length, ref_length):+.2f} % |",
        "",
        "## Qualifying pace: model flying lap vs each team's best qualifying lap",
        "",
    ]
    for (name, season), q in result["qualifying"].items():
        lines += [
            f"### {name}, {season} ({SEASONS[season]})",
            "",
            "| Team | Reference (s) | Driver | Model (s) | Error (s) | Relative error |",
            "|---|---|---|---|---|---|",
            *(f"| {team} | {ref:.3f} | {driver} | {sim:.3f} | {sim - ref:+.3f} | {100 * (sim - ref) / ref:+.2f} % |"
              for team, driver, ref, sim in q["rows"]),
            "",
            f"MAE {q['mae']:.3f} s, bias {q['bias']:+.3f} s, MAPE {q['mape']:.2f} %, max |error| {q['max']:.3f} s. "
            f"Fastest team: reference {q['fastest'][0]}, model {q['fastest'][1]}.",
            "",
        ]
    lines += ["## Pit loss: model pit_loss vs measured stops (drivers of the four modelled teams)", "",
              "| Config | Season | Stops | Measured median (s) | Measured range (s) | Model (s) | Error vs median (s) | MAE vs stops (s) |",
              "|---|---|---|---|---|---|---|---|"]
    for (name, season), p in result["pit_loss"].items():
        lines.append(f"| {name} | {season} ({SEASONS[season]}) | {p['n']} | {p['median']:.2f} "
                     f"| {p['range'][0]:.2f}-{p['range'][1]:.2f} | {p['model']:.2f} | {p['model'] - p['median']:+.2f} "
                     f"| {p['mae']:.2f} |")
    lines += ["", "## Race time: model car of the winning team, alone, pitting on the winner's laps (medium then hard assumed)", "",
              "| Config | Season | Winner | Laps | Stops on laps | Reference (s) | Model (s) | Error (s) | Relative error |",
              "|---|---|---|---|---|---|---|---|---|"]
    for (name, season), r in result["race"].items():
        lines.append(f"| {name} | {season} ({SEASONS[season]}) | {r['driver']} ({r['team']}) | {r['laps']} "
                     f"| {', '.join(map(str, r['stop_laps']))} | {r['time']:.3f} | {r['model']:.3f} "
                     f"| {r['model'] - r['time']:+.3f} | {100 * metrics.relative_error(r['model'], r['time']):+.2f} % |")
    errors = [metrics.relative_error(laps["calibrated"], record) for _, _, record, laps in result["circuits"]]
    lines += ["", "## All circuits: fastest model car's flying lap vs the race lap record (sanity check only)", "",
              "Not a validation: lap records are race laps, set by different cars in different years, and are usually "
              "slower than qualifying laps, which the grip was calibrated on. Circuit layouts are approximations "
              "(`tracks.py`): straight scale is the factor the estimated straights were stretched by to reach the "
              "official lap length.", "",
              "| Circuit | Straight scale | Record (s) | Model, baseline (s) | Model, calibrated (s) | Calibrated vs record |",
              "|---|---|---|---|---|---|"]
    for (name, scale, record, laps), error in zip(result["circuits"], errors):
        lines.append(f"| {name} | {scale:.2f} | {record:.3f} | {laps['baseline']:.3f} | {laps['calibrated']:.3f} "
                     f"| {100 * error:+.1f} % |")
    lines += ["", f"Calibrated vs record over {len(errors)} circuits: median {100 * statistics.median(errors):+.1f} %, "
              f"range {100 * min(errors):+.1f} % to {100 * max(errors):+.1f} %."]
    return "\n".join(lines) + "\n"


def main() -> None:
    text = render(evaluate())
    REPORT.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
