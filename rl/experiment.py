"""Minimal learning experiment: tune RuleBased's four thresholds with the cross-entropy method, then compare the
tuned policy with the baselines on held-out seeds. Writes rl/reports/experiment_report.md.

    python3 -m rl.experiment            # about 6-7 minutes on a laptop (each 53-lap episode takes ~2 s)

This is direct policy search over a hand-designed rule, not deep RL. Training and evaluation seeds never overlap.
"""
import random
import statistics
from dataclasses import fields
from pathlib import Path

from rl.env import StrategyEnv
from rl.evaluate import BASELINES, compare, run_episode, summarise, table
from rl.policies import RuleBased

REPORT = Path(__file__).resolve().parent / "reports" / "experiment_report.md"
BOUNDS = {"wear_limit": (0.3, 1.0), "neutral_from": (0.0, 0.8), "neutral_to": (0.2, 1.0), "final_call": (0.6, 0.98)}
SETTINGS = dict(laps=53, train_seeds=(0, 1, 2), eval_seeds=tuple(range(100, 120)), iterations=3, population=8,
                elites=2, cem_seed=0)


def cross_entropy_search(env: StrategyEnv, train_seeds, iterations: int, population: int, elites: int, cem_seed: int):
    """Gaussian CEM over the RuleBased thresholds; score = mean episode reward on the training seeds.

    Returns (best policy, history of (iteration, best score so far, elite mean score))."""
    rng = random.Random(cem_seed)
    names = [f.name for f in fields(RuleBased)]
    mean = list(RuleBased().as_vector())
    std = [(BOUNDS[n][1] - BOUNDS[n][0]) / 4 for n in names]

    def score(policy):
        return statistics.mean(run_episode(env, policy, seed)["reward"] for seed in train_seeds)

    best, best_score = RuleBased(), score(RuleBased())
    history = []
    for iteration in range(1, iterations + 1):
        candidates = []
        for _ in range(population):
            values = [min(max(rng.gauss(m, s), BOUNDS[n][0]), BOUNDS[n][1]) for n, m, s in zip(names, mean, std)]
            policy = RuleBased(**dict(zip(names, (round(v, 3) for v in values))))
            candidates.append((score(policy), policy))
        candidates.sort(key=lambda pair: pair[0], reverse=True)
        top = candidates[:elites]
        if top[0][0] > best_score:
            best_score, best = top[0]
        vectors = [policy.as_vector() for _, policy in top]
        mean = [statistics.mean(column) for column in zip(*vectors)]
        std = [max(statistics.pstdev(column), 0.02 * (BOUNDS[n][1] - BOUNDS[n][0])) for n, column in zip(names, zip(*vectors))]
        history.append((iteration, best_score, statistics.mean(s for s, _ in top)))
    return best, history


def main(settings: dict = SETTINGS) -> str:
    env = StrategyEnv(laps=settings["laps"])
    tuned, history = cross_entropy_search(env, settings["train_seeds"], settings["iterations"], settings["population"],
                                          settings["elites"], settings["cem_seed"])
    policies = {**BASELINES, "tuned rule-based (CEM)": lambda seed: tuned}
    results = compare(policies, settings["eval_seeds"], laps=settings["laps"])
    rows = summarise(results, "rule-based")
    n = len(settings["eval_seeds"])
    lines = [
        "# RL experiment report (generated)",
        "",
        "Generated by `python3 -m rl.experiment`. Do not edit by hand. Race times include penalties; lower is better.",
        "",
        "## Settings",
        "",
        f"- Environment: `StrategyEnv(laps={settings['laps']})`, defaults otherwise (McLaren, medium start, pit_loss 22 s, "
        "VSC/SC chance 0.5, rain chance 0.25, alone, two-compound rule on).",
        f"- Training seeds: {list(settings['train_seeds'])}. Evaluation seeds: {settings['eval_seeds'][0]}-{settings['eval_seeds'][-1]} "
        f"({n} episodes, disjoint from training).",
        f"- Cross-entropy method: {settings['iterations']} iterations x population {settings['population']}, "
        f"{settings['elites']} elites, seed {settings['cem_seed']}, bounds {BOUNDS}.",
        "",
        "## Training",
        "",
        "| Iteration | Best mean reward so far | Elite mean reward |",
        "|---|---|---|",
        *(f"| {i} | {best:.4f} | {elite:.4f} |" for i, best, elite in history),
        "",
        f"Starting thresholds (hand-set): {RuleBased()}",
        f"Tuned thresholds: {tuned}",
        "",
        f"## Evaluation on {n} held-out episodes",
        "",
        table(rows, "rule-based", n),
        "",
    ]
    text = "\n".join(lines)
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text(text)
    print(text)
    return text


if __name__ == "__main__":
    main()
